import { test, expect } from "./auth-fixture";
test("ajuste real: revisão, saldos persistidos, repetição, falta e cancelamento", async ({ page, request }) => {
  const f=JSON.parse(process.env.SALES_FIXTURE!);
  const post=async(path:string,data:unknown,key?:string)=>{const r=await request.post(`/api/${path}`,{data,headers:key?{"Idempotency-Key":key}:{}});expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
  const balance=async()=>Number((await (await request.get(`/api/estoques/saldo?idProduto=${f.product}&idLoja=${f.store}`)).json()).quantidadeAtual);
  const initial=await balance();
  await page.goto("/estoque/ajustes/novo");
  await page.getByLabel("Loja *",{exact:true}).selectOption(f.store);
  await page.getByLabel("Justificativa *",{exact:true}).fill("Correção integrada");
  await page.getByLabel("Produto *",{exact:true}).selectOption(f.product);
  await page.getByLabel("Quantidade *",{exact:true}).fill("2,125");
  await page.getByRole("button",{name:"Salvar rascunho",exact:true}).click();
  await expect(page).toHaveURL(/\/estoque\/ajustes\/[0-9a-f-]{36}$/);
  const url=page.url(),id=url.split("/").pop();
  expect(await balance()).toBeCloseTo(initial,3);
  await page.getByRole("button",{name:"Concluir ajuste",exact:true}).click();
  await page.getByRole("button",{name:"Confirmar ajuste",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Operação concluída");
  expect(await balance()).toBeCloseTo(initial+2.125,3);
  const done=await (await request.get(`/api/ajustes-estoque/${id}`)).json();
  expect(Number(done.itens[0].saldoAntes)).toBeCloseTo(initial,3);
  expect(Number(done.itens[0].saldoDepois)).toBeCloseTo(initial+2.125,3);
  await post(`ajustes-estoque/${id}/concluir`,{versao:0});
  expect(await balance()).toBeCloseTo(initial+2.125,3);
  const body={idLoja:f.store,justificativa:"Falta",itens:[{idProduto:f.product,tipo:"AJUSTE_SAIDA",quantidade:99999999999}]};
  const key=crypto.randomUUID(),draft=await post("ajustes-estoque",body,key);
  expect((await post("ajustes-estoque",body,key)).id).toBe(draft.id);
  const shortage=await request.post(`/api/ajustes-estoque/${draft.id}/concluir`,{data:{versao:draft.versao}});
  expect(shortage.status()).toBe(409);expect(await balance()).toBeCloseTo(initial+2.125,3);
  await post(`ajustes-estoque/${draft.id}/cancelar`,{versao:draft.versao,motivo:"Teste cancelado"});
  const mixed=await post("ajustes-estoque",{idLoja:f.store,justificativa:"Misto",itens:[{idProduto:f.product,tipo:"AJUSTE_SAIDA",quantidade:0.125},{idProduto:f.otherProduct,tipo:"AJUSTE_ENTRADA",quantidade:0.125}]},crypto.randomUUID());
  await post(`ajustes-estoque/${mixed.id}/concluir`,{versao:mixed.versao});expect(await balance()).toBeCloseTo(initial+2,3);
  await page.reload();await expect(page.getByText("Concluída por")).toBeVisible();
});
